function topFromProduct3(n) {
  for (const [top, re] of NAME_KW_3) if (re.test(n)) return top;
  return '';
}

function topFromName(name) {
  if (!name) return '';
  for (const [re, top] of NAME_RULES) if (re.test(name)) return top;
  return '';
}

function topFromProduct(productName) {
  for (const [top, re] of NAME_KW) if (re.test(productName)) return top;
  return '其他';
}

// ── 读数据 ──
const namesRaw = new Map(JSON.parse(fs.readFileSync(path.join(REF, 'lcode_names.json'), 'utf8')).map((x) => [x.code, x.name]));
const names = new Map(namesRaw);

/** l_code 没有名字时，用前缀逐级向上找（momo 分类码是分层的） */
function nameOf(code) {
  if (names.has(code)) return names.get(code);
  let c = code;
  for (let i = 0; i < 4; i++) {
    c = c.slice(0, -2) + '00';
    if (names.has(c)) return names.get(c);
    if (c.endsWith('0000')) break;
  }
  // 再试两位两位往上砍
  c = code;
  for (let i = 0; i < 3; i++) {
    c = c.slice(0, -2) + '00'.slice(0, c.length - (c.length - 2));
    if (names.has(c)) return names.get(c);
  }
  return '';
}
const rows = fs.readFileSync(path.join(REF, 'cat_map.jsonl'), 'utf8').trim().split('\n').map((l) => JSON.parse(l));

// 商品 → [l_code...]
const codeToLs = new Map();
for (const r of rows) {
  for (const c of r.codes) {
    if (!codeToLs.has(c)) codeToLs.set(c, []);
    codeToLs.get(c).push(r.l);
  }
}

const cat = JSON.parse(fs.readFileSync(CAT, 'utf8'));

// ── 投票推断：没有名字的 l_code，看它下面商品的多数分类 ──
const codeName = new Map(cat.items.map((it) => [String(it.code), it.name]));
const vote = new Map();   // l_code -> {top: count}
for (const [l, codeList] of (function () {
  const m = new Map();
  for (const r of rows) m.set(r.l, r.codes);
  return m;
})()) {
  const tally = {};
  for (const c of codeList) {
    const nm = codeName.get(String(c));
    if (!nm) continue;
    const t = topFromProduct2(nm) || topFromProduct(nm);
    if (t && t !== '其他') tally[t] = (tally[t] || 0) + 1;
  }
  const best = Object.entries(tally).sort((a, b) => b[1] - a[1])[0];
  if (best && best[1] >= 2) vote.set(l, { top: best[0], hits: best[1] });
}
console.log('投票推断出分类的 l_code:', vote.size);
let byLcode = 0, byName = 0;
const dist = {};

for (const it of cat.items) {
  const ls = codeToLs.get(String(it.code)) || [];
  let top = '', sub = '', l = '';

  // 优先取「有名字」的分类，名字越具体越好（取第一个有名字的）
  for (const code of ls) {
    const nm = nameOf(code);
    if (nm) {
      const t = topFromName(nm);
      if (t) { top = t; sub = nm; l = code; break; }
    }
  }
  if (top) byLcode++;
  else {
    // 没分类名：先看该 l_code 的多数分类，再用商品名兜底
    const v = ls.map((c) => vote.get(c)).find(Boolean);
    top = (v && v.top) || topFromProduct3(it.name) || topFromProduct2(it.name) || topFromProduct(it.name);
    sub = '';
    l = ls[0] || '';
    byName++;
    if (ls.length) byLcode++;   // 至少有分类归属
  }

  it.cat = top;
  it.sub = sub;
  it.l = l;
  dist[top] = (dist[top] || 0) + 1;
}

